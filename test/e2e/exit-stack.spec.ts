// M1 exit criteria that need the running stack but no browser (plan section 15, issue #33):
// the hostile corpus is refused with nothing written outside the job directory, the worker
// cannot reach the network, requests from an untrusted address get 403, a missing sentinel
// means not ready. Everything runs against the dev stack through the test proxy, like a user's
// browser would, with the files generated by `make e2e-fixtures`.

test.afterEach(async () => {
  await network.reset();
  await session.restore();
});

const hostileDir = path.join(fixturesDir, "hostile");
const mediaDir = path.join(fixturesDir, "media");

/** Everything of /data that is not the job's own directory (the job id is known by now). */
function outsideJob(id: string) {
  const own = `intake/jobs/${id}`;
  return (rel: string) => rel === own || rel.startsWith(`${own}/`);
}

// ---- The hostile corpus, end to end ----------------------------------------------------

type Skip = [name: string | null, reason: string];

interface Want {
  /** Set when the whole archive is refused: the archive's refusal code. */
  refused?: string;
  /** What the extraction skipped; a null name is not compared (cut or made printable). */
  skipped?: Skip[];
  /** Base names of the files that were written and registered. */
  files?: string[];
}

// With the default extensions: .txt is not accepted, so those entries are skipped as
// "extension". The same outcomes as internal/extract/corpus_test.go, seen through the API.
const hostile: Record<string, Want> = {
  "traversal.zip": {
    skipped: [
      ["../../evil.txt", "traversal"],
      ["ok.txt", "extension"],
    ],
  },
  "absolute.zip": { skipped: [["/etc/evil.txt", "absolute"]] },
  "drive-letter.zip": {
    skipped: [
      ["C:\\evil.txt", "backslash"],
      ["C:/evil2.txt", "drive_letter"],
    ],
  },
  "backslash.zip": { skipped: [["season\\..\\..\\evil.txt", "backslash"]] },
  "symlink.zip": {
    skipped: [
      ["link", "symlink"],
      ["dirlink", "symlink"],
      ["dirlink/evil.txt", "extension"],
    ],
  },
  "device.zip": {
    skipped: [
      ["tty", "special"],
      ["fifo", "special"],
      ["sock", "special"],
    ],
  },
  "bomb.zip": { refused: "ratio" },
  "lying-size.zip": { refused: "not_a_zip" },
  "too-many-entries.zip": { refused: "too_many_entries" },
  "many-directories.zip": { refused: "too_many_entries" },
  "nested.zip": { skipped: [["Season 01.zip", "nested_archive"]] },
  "renamed-non-video.zip": { files: ["Show - S01E01.mkv"] },
  "duplicate-names.zip": {
    files: ["Show - S01E01.mkv"],
    skipped: [["Show - S01E01.mkv", "duplicate"]],
  },
  "unicode-collision.zip": {
    files: ["Pok\u00e9mon.srt"],
    skipped: [[null, "duplicate"]],
  },
  "control-characters.zip": {
    files: ["badname.srt", "tabname.srt", "esc[31m.srt", "nul.srt"],
  },
  "long-name.zip": { skipped: [[null, "name_too_long"]] },
  "deep-nesting.zip": { skipped: [[null, "name_too_long"]] },
};

test("the corpus on disk and the expectations here are the same set", async () => {
  const onDisk = (await readdir(hostileDir)).filter((f) => f.endsWith(".zip")).sort();
  expect(onDisk).toEqual(Object.keys(hostile).sort());
});

test.describe("hostile corpus", () => {
  for (const [name, want] of Object.entries(hostile)) {
    test(name, async () => {
      const api = new Api("user1");
      const { id } = await api.createJob();
      const before = await data.list(outsideJob(id));

      await api.upload(id, path.join(hostileDir, name));
      await api.submit(id);
      const job = await api.settled(id);

      // Nothing in the corpus is a video that plays: the job ends without a usable file.
      expect(job.state).toBe("failed");
      expect(job.error?.code).toBe("no_usable_files");

      const archive = job.files.find((f) => f.kind === "archive");
      expect(archive, "the archive is in the job's file list").toBeDefined();
      if (want.refused) {
        expect(archive?.status).toBe("refused");
        expect(archive?.reason).toBe(want.refused);
        expect(archive?.extraction?.refused).toBe(want.refused);
      } else {
        expect(archive?.status).toBe("ok");
        expect(archive?.extraction?.refused ?? "").toBe("");
      }

      // Skipped entries, with their reasons.
      const skipped = archive?.extraction?.skipped ?? [];
      const wantSkipped = want.skipped ?? [];
      expect(skipped.map((s) => s.reason).sort()).toEqual(wantSkipped.map(([, r]) => r).sort());
      for (const [entry, reason] of wantSkipped) {
        if (entry !== null) expect(skipped).toContainEqual({ name: entry, reason });
      }

      // The files that were written and registered.
      const extracted = job.files.filter((f) => f.from === archive?.path).map((f) => f.name);
      expect(extracted.sort()).toEqual([...(want.files ?? [])].sort());
      // A renamed text file never passes the content check.
      for (const f of job.files.filter((f) => f.kind === "video")) {
        expect(f.status).toBe("refused");
      }

      // On disk: nothing changed outside the job's directory, and nothing in it is a link or a
      // special file.
      const after = await data.list(outsideJob(id));
      expect(diff(before, after), "changes outside intake/jobs/<job>").toEqual([]);
      const tree: Listing = await data.jobTree(id);
      expect(data.oddEntries(tree), "symlinks or special files in the job directory").toEqual([]);
      if (want.refused) {
        const left = [...tree.keys()].filter((k) => k.startsWith("files/"));
        expect(left, "a refused archive leaves nothing extracted").toEqual([]);
      }
    });
  }
});

// ---- A good upload, for contrast ---------------------------------------------------------

test.describe("good uploads", () => {
  test("a generated film ends in probed with its probe", async () => {
    const job = await new Api("user1").run(path.join(mediaDir, "film.mkv"));
    expect(job.state).toBe("probed");
    const film = job.files.find((f) => f.name === "film.mkv");
    expect(film?.status).toBe("ok");
    const probe = film?.probe as {
      durationMs: number;
      video: { codec: string }[];
      audio: unknown[];
    };
    expect(probe.durationMs).toBeGreaterThan(4000);
    expect(probe.video.length).toBeGreaterThan(0);
    expect(probe.audio.length).toBeGreaterThan(0);
  });

  test("a season zip ends in probed with a probe for every episode", async () => {
    const job = await new Api("user1").run(path.join(mediaDir, "Probe Show - Season 01.zip"));
    expect(job.state).toBe("probed");
    const videos = job.files.filter((f) => f.kind === "video");
    expect(videos.map((f) => f.name).sort()).toEqual([
      "Probe Show - S01E01.mkv",
      "Probe Show - S01E02.mkv",
    ]);
    for (const v of videos) {
      expect(v.status).toBe("ok");
      expect(v.probe).toMatchObject({ video: expect.any(Array), durationMs: expect.any(Number) });
    }
  });

  test("the manual fallback works: the test Radarr lists the uploaded video in the job's folder", async () => {
    const job = await new Api("user1").run(path.join(mediaDir, "film.mkv"));
    expect(job.state).toBe("probed");
    const radarr = job.manualImport.find((m) => m.app === "radarr");
    expect(radarr, "the job names Radarr's folder").toBeDefined();

    // A read-only request of the test Radarr (never a real one: the name is the stack's).
    const url = `${radarrURL}/api/v3/manualimport?${new URLSearchParams({
      folder: radarr?.folder ?? "",
      filterExistingFiles: "false",
    })}`;
    const res = await fetch(url, { headers: { "X-Api-Key": radarrKey } });
    expect(res.status).toBe(200);
    const items = (await res.json()) as { path: string; name: string }[];
    expect(items.map((i) => path.basename(i.path))).toEqual(["film.mkv"]);
  });
});

// ---- Requests from an untrusted address ------------------------------------------------

test.describe("untrusted address", () => {
  test("straight to the web process, even with the identity header, is 403", async () => {
    for (const p of ["/api/session", "/api/jobs", "/readyz"]) {
      const res = await fetch(webURL + p, { headers: { "Remote-User": "admin1" } });
      expect(res.status, p).toBe(403);
    }
    const post = await fetch(`${webURL}/api/jobs`, {
      method: "POST",
      headers: { "Remote-User": "admin1", Origin: "http://127.0.0.1:18080" },
    });
    expect(post.status).toBe(403);
  });

  test("the same request through the proxy is 200", async ({ page }) => {
    await loginAs(page, "admin1");
    const res = await page.request.get("/api/session", { headers: { "Remote-User": "admin1" } });
    expect(res.status()).toBe(200);
    expect((await res.json()).user.name).toBe("admin1");
  });

  test("identity headers a client sends through the proxy are ignored", async ({ page }) => {
    await loginAs(page, "user1");
    const res = await page.request.get("/api/session", {
      headers: {
        "Remote-User": "admin1",
        "Remote-Email": "admin1@example.com",
        "Remote-Groups": "users,media-admins",
      },
    });
    expect(res.status()).toBe(200);
    const info = await res.json();
    expect(info.user).toMatchObject({ name: "user1", admin: false });
    // And /readyz is for admins only: the forged groups do not make user1 one.
    const ready = await page.request.get("/readyz", {
      headers: { "Remote-User": "admin1", "Remote-Groups": "media-admins" },
    });
    expect(ready.status()).toBe(403);
  });
});

// ---- A missing sentinel means not ready ---------------------------------------------------

test("a missing sentinel: not ready, uploads refused with storage_unavailable, then ready again", async ({
  page,
}) => {
  await loginAs(page, "admin1");
  const ready = async () => {
    const res = await page.request.get("/readyz");
    return { status: res.status(), body: await res.json() };
  };
  const api = new Api("admin1");
  const { id } = await api.createJob();

  const first = await ready();
  expect(first.status).toBe(200);
  expect(first.body.checks).toContainEqual({ name: "sentinels", ok: true });

  await data.removeSentinel();
  try {
    await expect
      .poll(async () => (await ready()).status, { message: "/readyz without the sentinel" })
      .toBe(503);
    const down = await ready();
    expect(down.body.status).toBe("not_ready");
    expect(down.body.checks).toContainEqual(
      expect.objectContaining({ name: "sentinels", ok: false }),
    );

    const created = await api.createUpload(id, "film.mkv", 10);
    expect(created.status).toBe(503);
    expect(await created.text()).toContain("storage_unavailable");
  } finally {
    await data.restoreSentinel();
  }

  await expect
    .poll(async () => (await ready()).status, { message: "/readyz with the sentinel back" })
    .toBe(200);
  const created = await api.createUpload(id, "film.mkv", 10);
  expect(created.status).toBe(201);
  // Leave nothing behind: an unfinished upload counts against the user's parallel limit.
  await api.cancel(id);
});

// ---- The worker cannot reach the network ---------------------------------------------------

test.describe("worker isolation", () => {
  test("no network, read-only root, no capabilities", async () => {
    const cfg = (await stack.inspect("fukku-worker")).HostConfig;
    expect(cfg.NetworkMode).toBe("none");
    expect(cfg.ReadonlyRootfs).toBe(true);
    expect(cfg.CapDrop).toContain("ALL");
    expect(cfg.CapAdd ?? []).toEqual([]);
    expect(cfg.SecurityOpt).toContain("no-new-privileges:true");

    // In the running process: no effective capability, and the root cannot be written.
    const caps = await stack.exec("fukku-worker", [
      "grep",
      "^Cap\\(Eff\\|Prm\\|Bnd\\)",
      "/proc/self/status",
    ]);
    expect(
      caps.stdout
        .split("\n")
        .filter(Boolean)
        .map((l) => l.split(/\s+/)[1]),
    ).toEqual(["0000000000000000", "0000000000000000", "0000000000000000"]);
    const write = await stack.exec("fukku-worker", ["touch", "/isolation-probe"]);
    expect(write.code).not.toBe(0);
  });

  test("only the loopback interface exists", async () => {
    const res = await stack.exec("fukku-worker", ["cat", "/proc/net/dev"]);
    expect(res.code).toBe(0);
    const interfaces = res.stdout
      .split("\n")
      .slice(2)
      .map((l) => l.split(":")[0]?.trim())
      .filter(Boolean);
    expect(interfaces).toEqual(["lo"]);
  });

  test("a connection to the web container or to an outside address fails", async () => {
    // The web process listens on every network it is attached to; a worker with any network
    // could reach one of its addresses. 192.0.2.1 is in a documentation range: nothing
    // answers there on any network.
    const web = await stack.addresses("fukku-web");
    expect(web.length).toBeGreaterThan(0);
    const targets = [...web.map((ip) => [ip, "8080"] as const), ["192.0.2.1", "80"] as const];
    for (const [host, port] of targets) {
      const res = await stack.exec("fukku-worker", [
        "timeout",
        "5",
        "bash",
        "-c",
        'exec 3<>"/dev/tcp/$0/$1"',
        host,
        port,
      ]);
      expect(res.code, `connecting to ${host}:${port}: ${res.stderr}`).not.toBe(0);
    }
    // The failures above are the network's, not a missing shell.
    const tool = await stack.exec("fukku-worker", ["bash", "-c", "echo ok"]);
    expect(tool.stdout.trim()).toBe("ok");
  });

  test("its environment holds no API key", async () => {
    const res = await stack.exec("fukku-worker", ["env"]);
    expect(res.code).toBe(0);
    const names = res.stdout
      .split("\n")
      .map((l) => l.split("=")[0] ?? "")
      .filter(Boolean);
    expect(names).toContain("FUKKU_CONFIG"); // the environment was read
    expect(names.filter((n) => /API_?KEY|SECRET|TOKEN|PASSWORD/i.test(n))).toEqual([]);
    expect(res.stdout).not.toContain(radarrKey);
  });
});

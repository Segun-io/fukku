// Command notices writes THIRD_PARTY_NOTICES.md: the licences of everything Fukku redistributes
// that is not its own code. It is generated, not written by hand:
//
//   - the production npm packages of ui/package-lock.json (compiled into the UI bundle that the
//     binary embeds), with the licence files found in ui/node_modules (run `npm ci` first);
//   - the three bundled fonts (ui/src/assets/fonts/OFL-*.txt);
//   - the Go modules compiled into cmd/fukku (for linux/amd64 and linux/arm64) with their licence
//     files from the module cache, and the Go standard library;
//   - ffmpeg, mkvtoolnix and the Debian packages the Dockerfile installs, with the versions read
//     from the Dockerfile so that a bump there makes the check fail until this is regenerated.
//
// It fails on a licence that is not on the allow-list below (everything must be compatible
// with AGPL-3.0-only), and on a package whose licence text cannot be found.
//
//	go run ./tools/notices           write THIRD_PARTY_NOTICES.md
//	go run ./tools/notices -check    fail if the file on disk differs from what would be written
//
// It needs no network when ui/node_modules and the Go module cache are already populated, as they
// are in the development image after `make ui-deps` and the Go build and tests.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const outFile = "THIRD_PARTY_NOTICES.md"

// allowed is the allow-list of SPDX identifiers: permissive licences compatible with AGPL-3.0-only.
// Adding to it is a decision to make deliberately.
var allowed = map[string]bool{
	"MIT": true, "ISC": true, "Apache-2.0": true, "BSD-2-Clause": true, "BSD-3-Clause": true,
	"0BSD": true, "BlueOak-1.0.0": true, "Unlicense": true, "CC0-1.0": true, "Zlib": true,
	"OFL-1.1": true,
}

// licenseOverrides names the licence of an npm package whose package.json states none; the text
// must still be found in the package.
var licenseOverrides = map[string]string{
	"combine-errors": "MIT", // package.json has no licence field; License.md is the MIT text
}

// debianLicense is the licence of each Debian package the runtime image installs (by name). A
// package missing here fails the generator, so a new package gets its licence looked up.
var debianLicense = map[string]string{
	"ca-certificates": "MPL-2.0 (the certificate bundle), GPL-2.0-or-later (the update scripts)",
	"libdav1d7":       "BSD-2-Clause",
	"libx264-164":     "GPL-2.0-or-later",
	"mkvtoolnix":      "GPL-2.0-only",
	"tini":            "MIT",
}

type pkg struct {
	Name, Version, License string
	Texts                  []string
}

func main() {
	check := flag.Bool("check", false, "fail if "+outFile+" is out of date instead of writing it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	var b strings.Builder
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("Fukku is licensed under AGPL-3.0-only (`LICENSE`). The binary and the container image\n" +
		"redistribute the software below. This file is generated by `tools/notices` (`make notices`)\n" +
		"from `ui/package-lock.json`, the Go module graph and the `Dockerfile`; do not edit it. In the\n" +
		"image it is `/usr/share/doc/fukku/THIRD_PARTY_NOTICES.md`.\n\n")

	npm, err := npmPackages()
	if err != nil {
		return err
	}
	fonts, err := fontNotices()
	if err != nil {
		return err
	}
	gomods, err := goModules()
	if err != nil {
		return err
	}
	deb, err := imageComponents()
	if err != nil {
		return err
	}

	b.WriteString("## Image components (ffmpeg, mkvtoolnix, Debian)\n\n")
	b.WriteString(deb)
	b.WriteString("\n")
	writePackages(&b, "UI packages (npm, production dependencies bundled into the UI)", npm)
	b.WriteString("## Fonts (bundled with the UI)\n\n")
	b.WriteString(fonts)
	writePackages(&b, "Go modules compiled into the binary", gomods)

	out := []byte(strings.TrimRight(b.String(), "\n") + "\n")
	if check {
		have, err := os.ReadFile(outFile)
		if err != nil {
			return fmt.Errorf("%s is missing: run `make notices`", outFile)
		}
		if !bytes.Equal(have, out) {
			return fmt.Errorf("%s is out of date: run `make notices` and commit the result", outFile)
		}
		fmt.Println("notices: ok")
		return nil
	}
	return os.WriteFile(outFile, out, 0o644) //nolint:gosec // a public file in the repository, and read by non-root users in the image
}

// ---- npm --------------------------------------------------------------------------------

func npmPackages() ([]pkg, error) {
	raw, err := os.ReadFile("ui/package-lock.json")
	if err != nil {
		return nil, err
	}
	var lock struct {
		Packages map[string]struct {
			Version     string `json:"version"`
			License     string `json:"license"`
			Dev         bool   `json:"dev"`
			DevOptional bool   `json:"devOptional"`
		} `json:"packages"`
	}
	if err := json.Unmarshal(raw, &lock); err != nil {
		return nil, err
	}
	var out []pkg
	for path, p := range lock.Packages {
		if path == "" || p.Dev || p.DevOptional {
			continue
		}
		name := path[strings.LastIndex(path, "node_modules/")+len("node_modules/"):]
		dir := filepath.Join("ui", path)
		if _, err := os.Stat(dir); err != nil {
			return nil, fmt.Errorf("%s is not installed (run `make ui-deps`): %w", path, err)
		}
		lic := p.License
		if lic == "" {
			lic = licenseOverrides[name]
		}
		if err := checkLicense(name, lic); err != nil {
			return nil, err
		}
		texts, err := licenseFiles(dir)
		if err != nil {
			// Some packages ship no licence file. Their declared licence is then written out
			// from the standard text with the author named in package.json.
			t, serr := synthesizeLicense(dir, lic)
			if serr != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
			texts = []string{t}
		}
		out = append(out, pkg{Name: name, Version: p.Version, License: lic, Texts: texts})
	}
	return out, nil
}

var spdxToken = regexp.MustCompile(`[A-Za-z0-9.+-]+`)

// checkLicense accepts an SPDX expression when every term of an AND, or at least one term of an
// OR, is on the allow-list.
func checkLicense(name, expr string) error {
	if strings.TrimSpace(expr) == "" {
		return fmt.Errorf("%s: no licence declared", name)
	}
	var terms []string
	for _, t := range spdxToken.FindAllString(expr, -1) {
		if t != "AND" && t != "OR" && t != "WITH" {
			terms = append(terms, t)
		}
	}
	if strings.Contains(expr, " AND ") {
		for _, t := range terms {
			if !allowed[t] {
				return fmt.Errorf("%s: licence %q (%s) is not on the allow-list", name, t, expr)
			}
		}
		return nil
	}
	for _, t := range terms {
		if allowed[t] {
			return nil
		}
	}
	return fmt.Errorf("%s: licence %q is not on the allow-list", name, expr)
}

var licenseName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|unlicense)([-._].*)?$`)

// licenseFiles returns the text of every licence or notice file at the top of dir, in name order.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var texts []string
	for _, e := range entries {
		if e.IsDir() || !licenseName.MatchString(e.Name()) {
			continue
		}
		ext := strings.ToLower(filepath.Ext(e.Name()))
		if ext == ".js" || ext == ".ts" || ext == ".json" {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name())) //nolint:gosec // paths come from the lockfile, the module cache and fixed names in this repository
		if err != nil {
			return nil, err
		}
		if t := normalize(string(raw)); t != "" {
			texts = append(texts, t)
		}
	}
	if len(texts) == 0 {
		return nil, errors.New("no licence file found in the package")
	}
	return texts, nil
}


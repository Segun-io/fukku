var emailInBrackets = regexp.MustCompile(`\s*<[^>]*>`)

// synthesizeLicense writes the standard MIT or ISC text for a package without a licence file,
// naming the author from its package.json (without an email address).
func synthesizeLicense(dir, lic string) (string, error) {
	body := map[string]string{"MIT": mitText, "ISC": iscText}[lic]
	if body == "" {
		return "", errors.New("no licence file, and no standard text for " + lic)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "package.json")) //nolint:gosec // paths come from the lockfile, the module cache and fixed names in this repository
	if err != nil {
		return "", err
	}
	var pj struct {
		Author any `json:"author"`
	}
	if err := json.Unmarshal(raw, &pj); err != nil {
		return "", err
	}
	author := ""
	switch a := pj.Author.(type) {
	case string:
		author = a
	case map[string]any:
		author, _ = a["name"].(string)
	}
	author = strings.TrimSpace(emailInBrackets.ReplaceAllString(author, ""))
	if author == "" {
		return "", errors.New("no licence file and no author in package.json")
	}
	return "(The package ships no licence file; this is the standard " + lic + " text with the author named in its package.json.)\n\nCopyright (c) " + author + "\n\n" + body, nil
}

func normalize(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t")
	}
	return strings.Trim(strings.Join(lines, "\n"), "\n")
}

// ---- fonts ------------------------------------------------------------------------------

func fontNotices() (string, error) {
	dir := "ui/src/assets/fonts"
	files, err := filepath.Glob(filepath.Join(dir, "OFL-*.txt"))
	if err != nil || len(files) == 0 {
		return "", fmt.Errorf("no OFL-*.txt in %s", dir)
	}
	sort.Strings(files)
	have := map[string]bool{}
	var b strings.Builder
	for _, f := range files {
		name := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(f), "OFL-"), ".txt")
		have[name] = true
		raw, err := os.ReadFile(f) //nolint:gosec // paths come from the lockfile, the module cache and fixed names in this repository
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "### %s (OFL-1.1)\n\n%s\n\n", name, fence(normalize(string(raw))))
	}
	woff, _ := filepath.Glob(filepath.Join(dir, "*.woff2"))
	for _, w := range woff {
		base := filepath.Base(w)
		i := strings.Index(base, "-latin")
		if i < 0 || !have[base[:i]] {
			return "", fmt.Errorf("font %s has no OFL-<name>.txt next to it", base)
		}
	}
	return b.String(), nil
}

// ---- Go modules -------------------------------------------------------------------------

func goModules() ([]pkg, error) {
	type mod struct{ path, version, dir string }
	mods := map[string]mod{}
	for _, arch := range []string{"amd64", "arm64"} {
		cmd := exec.CommandContext(context.Background(), "go", "list", "-deps", "-f",
			"{{if not .Standard}}{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}{{end}}", "./cmd/fukku")
		cmd.Env = append(os.Environ(), "GOOS=linux", "GOARCH="+arch, "CGO_ENABLED=0")
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		raw, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list: %w: %s", err, stderr.String())
		}
		for _, line := range strings.Split(strings.TrimSpace(string(raw)), "\n") {
			f := strings.Fields(line)
			if len(f) == 3 {
				mods[f[0]] = mod{f[0], f[1], f[2]}
			}
		}
	}
	var out []pkg
	for _, m := range mods {
		texts, err := licenseFiles(m.dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.path, err)
		}
		lic, err := detectLicense(texts)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.path, err)
		}
		if err := checkLicense(m.path, lic); err != nil {
			return nil, err
		}
		out = append(out, pkg{Name: m.path, Version: m.version, License: lic, Texts: texts})
	}
	// The standard library is compiled in too; its licence is in GOROOT.
	root, err := exec.CommandContext(context.Background(), "go", "env", "GOROOT").Output()
	if err != nil {
		return nil, err
	}
	ver, err := exec.CommandContext(context.Background(), "go", "env", "GOVERSION").Output()
	if err != nil {
		return nil, err
	}
	raw, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(root)), "LICENSE"))
	if err != nil {
		return nil, err
	}
	out = append(out, pkg{Name: "Go standard library", Version: strings.TrimSpace(string(ver)), License: "BSD-3-Clause", Texts: []string{normalize(string(raw))}})
	return out, nil
}

// detectLicense names a Go module's licence from its text; an unrecognised text fails, so a new
// kind of licence is looked at by a person.
func detectLicense(texts []string) (string, error) {
	all := strings.Join(texts, "\n")
	switch {
	case strings.Contains(all, "Apache License") && strings.Contains(all, "Version 2.0"):
		return "Apache-2.0", nil
	case strings.Contains(all, "Permission is hereby granted, free of charge"):
		return "MIT", nil
	case strings.Contains(all, "Redistribution and use in source and binary forms") && strings.Contains(all, "Neither the name"):
		return "BSD-3-Clause", nil
	case strings.Contains(all, "Redistribution and use in source and binary forms"):
		return "BSD-2-Clause", nil
	}
	return "", errors.New("licence text not recognised: add it to detectLicense after reading it")
}

// ---- image components -------------------------------------------------------------------

var aptLine = regexp.MustCompile(`^\s*([a-z0-9][a-z0-9.+-]*)=(\S+)`)

func imageComponents() (string, error) {
	raw, err := os.ReadFile("Dockerfile")
	if err != nil {
		return "", err
	}
	text := string(raw)
	ffv := regexp.MustCompile(`(?m)^ARG FFMPEG_VERSION=(\S+)$`).FindStringSubmatch(text)
	if ffv == nil {
		return "", errors.New("FFMPEG_VERSION not found in the Dockerfile")
	}
	i := strings.LastIndex(text, "\nFROM ${RUNTIME_IMAGE}")
	if i < 0 {
		return "", errors.New("runtime stage not found in the Dockerfile")
	}
	var debs [][2]string
	stage := text[i:]
	start := strings.Index(stage, "apt-get install")
	end := strings.Index(stage, "rm -rf /var/lib/apt/lists")
	if start < 0 || end < start {
		return "", errors.New("the apt-get install command of the runtime stage was not found")
	}
	for _, l := range strings.Split(stage[start:end], "\n") {
		if m := aptLine.FindStringSubmatch(l); m != nil {
			debs = append(debs, [2]string{m[1], m[2]})
		}
	}
	if len(debs) == 0 {
		return "", errors.New("no pinned Debian packages found in the runtime stage")
	}
	sort.Slice(debs, func(a, c int) bool { return debs[a][0] < debs[c][0] })

	var b strings.Builder
	b.WriteString("The image installs these Debian packages in its runtime stage (versions from the\n" +
		"`Dockerfile`; the licence text of each is `/usr/share/doc/<package>/copyright` in the image):\n\n")
	b.WriteString("| Package | Version | Licence |\n| --- | --- | --- |\n")
	for _, d := range debs {
		lic, ok := debianLicense[d[0]]
		if !ok {
			return "", fmt.Errorf("debian package %s has no entry in debianLicense: look up its licence and add it", d[0])
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", d[0], d[1], lic)
	}
	b.WriteString("\nThe Debian base image and the libraries the packages above depend on (Qt, Boost, ICU, ...)\n" +
		"are Debian packages too, each with its licence in `/usr/share/doc/<package>/copyright`.\n\n")
	fmt.Fprintf(&b, "`ffmpeg` and `ffprobe` are built from the upstream FFmpeg %s source tarball with\n"+
		"`--enable-gpl --enable-libx264`, so the binaries are licensed GPL-2.0-or-later (the build\n"+
		"links libx264, which is GPL; Fukku itself is AGPL-3.0-only). Their licence texts are\n"+
		"`/usr/share/doc/fukku/ffmpeg/LICENSE.md` and `COPYING.GPLv2` in the image. They also link\n"+
		"zlib (zlib licence; `/usr/share/doc/zlib1g/copyright`) statically. The corresponding source is\n"+
		"the pinned tarball and the Debian source packages of `x264` and `dav1d` at the snapshot date;\n"+
		"see `docs/image.md` (Source offer).\n", ffv[1])
	return b.String(), nil
}

// ---- output -----------------------------------------------------------------------------

// fence wraps text in a code fence long enough not to be closed by anything inside it.
func fence(s string) string {
	f := "```"
	for strings.Contains(s, f) {
		f += "`"
	}
	return f + "text\n" + s + "\n" + f
}

// writePackages lists the packages (name, version, licence), then each distinct licence text
// once with the packages that carry it, so that the many identical MIT texts are not repeated.
func writePackages(b *strings.Builder, title string, pkgs []pkg) {
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].Name+"@"+pkgs[i].Version < pkgs[j].Name+"@"+pkgs[j].Version })
	fmt.Fprintf(b, "## %s\n\n| Package | Version | Licence |\n| --- | --- | --- |\n", title)
	for _, p := range pkgs {
		fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", p.Name, p.Version, p.License)
	}
	b.WriteString("\n")

	groups := map[string][]string{}
	var order []string
	for _, p := range pkgs {
		key := strings.Join(p.Texts, "\n\n-----\n\n")
		if _, ok := groups[key]; !ok {
			order = append(order, key)
		}
		groups[key] = append(groups[key], p.Name+" "+p.Version)
	}
	for _, key := range order {
		fmt.Fprintf(b, "Licence text for: %s\n\n%s\n\n", strings.Join(groups[key], ", "), fence(key))
	}
}
